import { describe, expect, it } from "vitest";
import { contactSchema } from "@/lib/contact-schema";
import { MAX_INPUT_CHARS } from "@/lib/rag/types";
import { clip } from "@/lib/text";

describe("contact form schema", () => {
  const valid = { name: "Ada", email: "ada@example.com", message: "Hello, I'd like to chat about a role." };

  it("accepts a valid message and trims whitespace", () => {
    const parsed = contactSchema.parse({ ...valid, name: "  Ada  ", email: " ada@example.com " });
    expect(parsed.name).toBe("Ada");
    expect(parsed.email).toBe("ada@example.com");
  });

  it.each([
    ["name", { ...valid, name: "   " }],
    ["email", { ...valid, email: "not-an-email" }],
    ["message", { ...valid, message: "too short" }],
    ["message", { ...valid, message: "x".repeat(2001) }],
  ])("rejects an invalid %s", (field, input) => {
    const result = contactSchema.safeParse(input);
    expect(result.success).toBe(false);
    expect(result.error?.issues[0].path[0]).toBe(field);
  });
});

describe("clip", () => {
  it("leaves short text alone", () => {
    expect(clip("Short", 20)).toBe("Short");
  });

  it("cuts at a word boundary and drops dangling punctuation", () => {
    expect(clip("Every number is computed, never generated by the model", 32)).toBe("Every number is computed...");
  });
});

describe("assistant input limit", () => {
  it("matches the documented 500 characters", () => {
    expect(MAX_INPUT_CHARS).toBe(500);
  });
});
